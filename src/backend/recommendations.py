def get_recommendation(class_name):

    # =================================================
    # HEALTHY
    # =================================================

    if "healthy" in class_name.lower():

        return {
            "status": "healthy",

            "message":
                "The plant appears healthy. Continue regular monitoring and proper plant care.",

            "actions": [
                "Continue regular monitoring.",
                "Maintain appropriate irrigation.",
                "Maintain balanced plant nutrition.",
                "Monitor for any new symptoms."
            ]
        }


    # =================================================
    # DISEASE
    # =================================================

    recommendation = recommendations.get(class_name)

    if recommendation:

        return {
            "status": "attention",
            **recommendation
        }


    # =================================================
    # UNKNOWN
    # =================================================

    return {
        "status": "unknown",

        "message":
            "No specific recommendation is available for this condition.",

        "actions": [
            "Monitor the plant regularly.",
            "Take a clearer image if possible.",
            "Consult an agricultural specialist if symptoms continue."
        ]
    }
